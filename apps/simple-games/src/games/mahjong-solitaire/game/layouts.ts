/**
 * The board layouts — hand-made coordinate data, one witness order each
 * (docs/MAHJONG_SOLITAIRE_RULES.md §1, §5), and the level table that deals
 * them out (§6).
 *
 * Every layout here is proven peelable: an order exists that removes all of
 * its tiles two free tiles at a time. layouts.test.ts re-proves it on every
 * run — with a bounded backtracking search AND by replaying the witness — so
 * a layout that cannot be finished cannot ship. That proof is what lets the
 * generator promise a winnable deal without a retry loop (§5): the runtime
 * search may give up at its node cap, but the witness is always there to
 * fall back to, so "generation failed" is not a state this game has.
 *
 * The witness orders were computed offline by the same backtracking search
 * the tests run (seed `<id>:witness`) and are shipped as data, not re-derived:
 * a witness only has to BE a valid order, not come from anywhere special.
 *
 * Coordinates are half-tile units (a tile covers 2×2), listed sorted by
 * z, then y, then x — which is also the paint order the board renders in.
 * All layouts are portrait and at most 8 columns wide: the static mock
 * measured 8 columns as comfortably readable at a 320px viewport, so the
 * planned 9-column ceiling was never needed (§12).
 */
import type { GameMode } from './types';

export interface LayoutTile {
  readonly x: number;
  readonly y: number;
  readonly z: number;
}

export type LayoutId =
  | 'sprout'
  | 'steps'
  | 'terrace'
  | 'courtyard'
  | 'pagoda'
  | 'lantern'
  | 'bridge'
  | 'keep'
  | 'garden'
  | 'turtle';

export interface Layout {
  readonly id: LayoutId;
  readonly tiles: readonly LayoutTile[];
  /**
   * A proven removal order, flattened pairs of tile indices: tiles at
   * positions witness[2k] and witness[2k+1] are the k-th pair removed.
   */
  readonly witness: readonly number[];
}

function unflattenTiles(flat: readonly number[]): LayoutTile[] {
  const out: LayoutTile[] = [];
  for (let i = 0; i < flat.length; i += 3) {
    out.push({ x: flat[i]!, y: flat[i + 1]!, z: flat[i + 2]! });
  }
  return out;
}

