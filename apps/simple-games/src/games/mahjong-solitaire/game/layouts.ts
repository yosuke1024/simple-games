export const MAX_LEVEL = 100;

export const clampLevel = (level: number): number =>
  Math.min(MAX_LEVEL, Math.max(1, Math.floor(level)));

/** The canonical seed — identity is the only truth a save keeps (§10). */
export function levelSeed(level: number): string {
  return `mj-level-${clampLevel(level)}`;
}

/**
 * What a level deals (§6): a layout, and the stock mix. `quads` ordinary
 * faces appear four times (two pairs — the real mahjong difficulty of picking
 * WHICH two of four to pair), `twins` appear twice, and the bonus groups
 * contribute `flowers` + `seasons` tiles of distinct faces. All four terms
 * are even-friendly by construction: 4·quads + 2·twins + flowers + seasons
 * equals the layout's tile count, and levels.test.ts re-checks that.
 */
export interface LevelParams {
  readonly layoutId: LayoutId;
  readonly quads: number;
  readonly twins: number;
  readonly flowers: number;
  readonly seasons: number;
}

interface LevelBand extends LevelParams {
  readonly from: number;
  readonly to: number;
}

/** The table of §6, verbatim. The last band is the full standard set. */
const BANDS: readonly LevelBand[] = [
  { from: 1, to: 8, layoutId: 'sprout', quads: 0, twins: 12, flowers: 0, seasons: 0 },
  { from: 9, to: 16, layoutId: 'steps', quads: 3, twins: 12, flowers: 0, seasons: 0 },
  { from: 17, to: 25, layoutId: 'terrace', quads: 6, twins: 12, flowers: 0, seasons: 0 },
  { from: 26, to: 35, layoutId: 'courtyard', quads: 9, twins: 10, flowers: 2, seasons: 2 },
  { from: 36, to: 45, layoutId: 'pagoda', quads: 12, twins: 10, flowers: 2, seasons: 2 },
  { from: 46, to: 56, layoutId: 'lantern', quads: 15, twins: 10, flowers: 2, seasons: 2 },
  { from: 57, to: 67, layoutId: 'bridge', quads: 19, twins: 8, flowers: 2, seasons: 2 },
  { from: 68, to: 78, layoutId: 'keep', quads: 23, twins: 6, flowers: 2, seasons: 2 },
  { from: 79, to: 89, layoutId: 'garden', quads: 26, twins: 4, flowers: 4, seasons: 4 },
  { from: 90, to: MAX_LEVEL, layoutId: 'turtle', quads: 34, twins: 0, flowers: 4, seasons: 4 },
];

export function levelParams(level: number): LevelParams {
  const target = clampLevel(level);
  for (const band of BANDS) if (target <= band.to) return band;
  return BANDS[BANDS.length - 1]!;
}

/** The daily is always the flagship: the full 144-tile turtle (§6). */
export const DAILY_PARAMS: LevelParams = {
  layoutId: 'turtle',
  quads: 34,
  twins: 0,
  flowers: 4,
  seasons: 4,
};

export function paramsFor(mode: GameMode, level: number | null): LevelParams {
  return mode === 'daily' ? DAILY_PARAMS : levelParams(level ?? 1);
}
