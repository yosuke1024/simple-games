/**
 * The v1 catalog's data (docs/TANGRAM_RULES.md §2「v1 のカタログ」): 13 Easy,
 * 12 Medium, 9 Hard. Order within a tier is play order (§6); ids are stable
 * names, never shown (§2). catalog.test.ts checks every invariant of §2 on
 * every entry, independently of how the entry was made.
 *
 * Coordinates are `[xa, xb, ya, yb]` — x = xa + xb√2, y = ya + yb√2 — in
 * units of half the small triangle's leg (§5). A solution entry is
 * `[r, f, at]` (§5「姿」).
 *
 * Where the entries come from (§2「由来」, all the author's own):
 * - Easy 1–3 (`square`, `triangle`, `parallelogram`) are the Phase 0
 *   prototype's silhouettes rewritten in Z[√2]: the square's solution is the
 *   table in §2, and the other two map the square solution's two halves by
 *   the prototype's isometries.
 * - Easy 4–13 are the other ten convex shapes seven pieces can form (with the
 *   three above, the thirteen convex tangram shapes). Their outlines came
 *   from enumerating convex 8-direction polygons of area 32, and each
 *   solution from a throwaway exact tiling search — dev-time only, not
 *   shipped.
 * - Medium and Hard: arrangements proposed by a throwaway dev-time tool that
 *   joins the seven pieces edge to edge at random, filtered to simple
 *   outlines with no edge shorter than a small triangle's leg; the author
 *   looked at the rendered candidates, chose these, turned each to read as
 *   an object, and assigned the tiers (Medium 6–9 outline vertices, Hard
 *   10–13). Medium fixes `L1` and `P`, the default of §3.
 */
import type { Figure, Tier } from './catalog';
import type { PieceId, Pose } from './pieces';
import type { Pt } from './z2';

type Entry = readonly [r: number, f: 0 | 1, at: Pt];

function fig(
  id: string,
  tier: Tier,
  outline: readonly Pt[],
  solution: Readonly<Record<PieceId, Entry>>,
  fixed: readonly PieceId[],
): Figure {
  const poses = Object.fromEntries(
    Object.entries(solution).map(([piece, [r, f, at]]) => [piece, { r, f, at }]),
  ) as Record<PieceId, Pose>;
  return { id, tier, outline, solution: poses, fixed, origin: 'original' };
}

