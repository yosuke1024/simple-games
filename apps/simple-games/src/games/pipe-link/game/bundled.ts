/** Decodes one bundled board; throws if it does not decode (the tests make sure it always does). */
export function decodeBundled(
  difficulty: Difficulty,
  entry: BundledBoard,
): { readonly board: Board; readonly solution: number[]; readonly initial: number[] } {
  const { width, height } = PRESETS[difficulty];
  const parts = decodeParts(
    {
      types: entry.types,
      source: entry.source,
      solution: entry.solution,
      initial: entry.initial,
      current: entry.initial,
    },
    width,
    height,
  );
  if (parts === null) throw new Error(`bundled board ${entry.seed} does not decode`);
  return { board: parts.board, solution: parts.solution, initial: parts.initial };
}
