/**
 * The shapes of Bounce Up's state (docs/BOUNCE_UP_RULES.md §2–§4). Every
 * number in them is an integer: positions in 1/120 px, speeds in px/s.
 */

export type PlatformWidth = 'normal' | 'wide';
export type PlatformKind = 'static' | 'moving' | 'vanishing';
export type RunStatus = 'ready' | 'running' | 'paused' | 'over';
/** What one step did, for the UI's sounds and redraws (§7). */
export type StepEvent = 'none' | 'bounce' | 'vanish' | 'over';

/** A moving platform's triangle wave (§3): left end, travel, speed, phase. */
export interface Motion {
  /** Left edge at the wave's low end, units. */
  readonly lo: number;
  /** Travel, units (> 0). */
  readonly span: number;
  /** px/s = units per step. */
  readonly speed: number;
  /** Phase, units in [0, 2·span). */
  readonly phase: number;
}

export interface Platform {
  /** Segment × 2 for the chain platform, segment × 2 + 1 for the extra. */
  readonly id: number;
  readonly segment: number;
  readonly kind: PlatformKind;
  /** On the safety chain (§3): always static. */
  readonly chain: boolean;
  /** Height of the top surface, units. */
  readonly top: number;
  /** Left edge, units (a moving platform's comes from `motion` and the tick). */
  readonly left: number;
  /** Width, units. */
  readonly width: number;
  readonly motion: Motion | null;
}

/** The prefix the next segment is built on (§3「決定性」). */
export interface GenCursor {
  /** The next segment index to generate. */
  readonly next: number;
  /** Height of the last generated chain platform's top, units. */
  readonly chainTop: number;
  /** Centre of the last generated chain platform, whole px. */
  readonly chainCenterPx: number;
}

export interface RunState {
  readonly seed: string;
  readonly width: PlatformWidth;
  readonly status: RunStatus;
  /** Steps run while `running` (moving platforms read it). */
  readonly tick: number;
  /** Body: foot centre x in [0, BOARD_WIDTH), foot height y, vertical speed. */
  readonly x: number;
  readonly y: number;
  readonly vy: number;
  /** The target x, continuous (never wrapped on its own — §4). */
  readonly target: number;
  /** The held direction last step (keys / ◀ ▶), −1 / 0 / 1. */
  readonly heldDir: number;
  /** The bottom edge of the view, units; never decreases (§2). */
  readonly cameraBottom: number;
  /** The highest foot height reached, units (§4). */
  readonly maxHeight: number;
  /** The highest segment landed on (§4). */
  readonly reachedSegment: number;
  /** Platforms alive, lowest first (vanished ones are removed). */
  readonly platforms: readonly Platform[];
  readonly gen: GenCursor;
  /** What the last step did. */
  readonly event: StepEvent;
  /** Segments generated by the last step (§11 work bound). */
  readonly generatedLastStep: number;
  /** Steps whose generation stopped at GEN_PER_STEP_LIMIT (§11). */
  readonly genCapHits: number;
}

/** One step's input (§4): finger movement in units, held direction. */
export interface StepInput {
  readonly drag: number;
  readonly dir: number;
}
